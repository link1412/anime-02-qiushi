#!/bin/bash
# Final encode (runs on the Mac mini): PNG frames + synthesised audio -> phone-like H.264 MP4.
# Metadata states plainly that this is rendered, not filmed. No camera make/model tags are written.
set -euo pipefail
EP1=${EP1:-/path/to/ep1}
FF=/opt/homebrew/bin/ffmpeg
OUT=${OUT:-$EP1/out/shishiqiushi.mp4}
mkdir -p "$(dirname "$OUT")"
NOTE='Rendered, not filmed. Computer-generated simulation of phone recordings of a laptop screen. The chat UI frames were captured from OpenCode driven by a scripted mock model server; every reply, tool call and error shown was written in advance, not generated by a model or returned by any real API. "Mythos 10" and the effort "Ululululultra" are fictional; the web pages fetched on screen were local stub pages. Sound is synthesised. / 渲染生成，非拍摄：模拟手机对屏录像的计算机生成画面；界面来自由脚本化模拟服务驱动的 OpenCode，所有回复、工具调用和报错均为预先写定，并非模型生成或真实接口返回；“Mythos 10”与“Ululululultra”为虚构；画面中抓取的网页是本地占位页；声音为合成。'
$FF -hide_banner -y \
  -framerate 30 -start_number 0 -i "$EP1/build/frames/f_%05d.png" \
  -i "$EP1/build/audio.wav" \
  -map 0:v -map 1:a \
  -vf "scale=out_color_matrix=bt709:out_range=tv:flags=lanczos+accurate_rnd,format=yuv420p" \
  -c:v libx264 -profile:v high -level 4.2 -preset slow \
  -b:v 16M -maxrate 20M -bufsize 32M -g 30 -bf 0 \
  -colorspace bt709 -color_primaries bt709 -color_trc bt709 -color_range tv \
  -c:a aac_at -b:a 192k -ar 48000 \
  -shortest -movflags +faststart -map_metadata -1 \
  -metadata title='实事求是' \
  -metadata comment="$NOTE" \
  -metadata description="$NOTE" \
  -metadata:s:v:0 handler_name='Rendered video (not camera footage)' \
  -metadata:s:a:0 handler_name='Synthesised audio' \
  "$OUT"
echo "exit=$? out=$OUT"
