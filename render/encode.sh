#!/bin/bash
# Final encode (runs on the Mac mini): PNG frames + synthesised audio -> phone-like H.264 MP4.
# Metadata states plainly that this is rendered, not filmed. No camera make/model tags are written.
set -euo pipefail
EP1=${EP1:-/path/to/ep1}
FF=/opt/homebrew/bin/ffmpeg
OUT=${OUT:-$EP1/out/shishiqiushi.mp4}
mkdir -p "$(dirname "$OUT")"
NOTE='Rendered, not filmed. Computer-generated simulation of a phone recording of a laptop screen. The chat UI frames were captured from OpenCode driven by a scripted mock model server; the replies shown were written in advance, not generated by a model. Sound is synthesised, except the lighter, cigarette draw and exhale, which are CC0 (public domain) recordings by Joseph Sardin, BigSoundBank.com. / 渲染生成，非拍摄：模拟手机对屏录像的计算机生成画面；界面来自由脚本化模拟服务驱动的 OpenCode，回复为预先写定，并非模型实时生成；声音为合成，其中打火机、吸烟、吐气为 BigSoundBank（Joseph Sardin）的 CC0 公有领域录音。'
SRC=(-framerate 30 -start_number 0 -i "$EP1/build/frames/f_%05d.png")
if [ "${PHONE_GEN:-1}" = "1" ]; then
  # generation 1 = what the phone would have written: HEVC ~10 Mbit/s, 1 s GOP, every clip
  # (a separate recording) starts on a keyframe. Moire/fine detail is what the codec loses first.
  # The deliverable below is then a transcode of it (like any uploaded phone video).
  CUTS=$(cd "$EP1" && python3 -c "import sys; sys.path.insert(0,'render'); import camera; print(','.join(f'{c.t0:.4f}' for c in camera.RIG.clips))")
  GEN1="$EP1/build/phone_gen1.mov"
  $FF -hide_banner -y "${SRC[@]}" \
    -vf "scale=out_color_matrix=bt709:out_range=tv:flags=lanczos+accurate_rnd,format=yuv420p" \
    -c:v libx265 -preset medium -tag:v hvc1 -b:v 10M -maxrate 12M -bufsize 20M \
    -x265-params "keyint=30:min-keyint=1:scenecut=0:log-level=error" -force_key_frames "$CUTS" \
    -colorspace bt709 -color_primaries bt709 -color_trc bt709 -color_range tv -an "$GEN1"
  SRC=(-i "$GEN1")
fi
$FF -hide_banner -y \
  "${SRC[@]}" \
  -i "$EP1/build/audio.wav" \
  -map 0:v -map 1:a \
  -vf "scale=out_color_matrix=bt709:out_range=tv:flags=lanczos+accurate_rnd,format=yuv420p" \
  -c:v libx264 -profile:v high -level 4.2 -preset slow \
  -b:v 16M -maxrate 20M -bufsize 32M -g 30 -bf 0 \
  -colorspace bt709 -color_primaries bt709 -color_trc bt709 -color_range tv \
  -c:a aac_at -b:a 192k -ar 48000 \
  -shortest -movflags +faststart -map_metadata -1 \
  -metadata title='实事求是' \
  -metadata comment="$NOTE" \
  -metadata description="$NOTE" \
  -metadata:s:v:0 handler_name='Rendered video (not camera footage)' \
  -metadata:s:a:0 handler_name='Synthesised audio' \
  "$OUT"
echo "exit=$? out=$OUT"
